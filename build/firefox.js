// The Firefox generator: a Manifest V2 extension in dist/firefox/. Every
// file is text except icon.png, which is a Buffer.
import { readFileSync } from 'node:fs';
import { techniquesFor, isEmpty, hasTechniques } from './techniques.js';
import { matchPatternToRegExp } from './match-pattern.js';
import { statementsAt, guarded } from './page-placement.js';
import { indent } from './page-code.js';
import * as engine from './firefox-runtime.js';
import * as runtime from './runtime.js';
import * as options from './firefox-options.js';

export const FIREFOX_DIR = 'dist/firefox';

const ICON = readFileSync(new URL('./assets/icon.png', import.meta.url));
const LICENSE = readFileSync(new URL('../LICENSE.txt', import.meta.url), 'utf8');

const NETWORK = ['blockRequests', 'blockCookies', 'setRequestHeader'];

// One content script per moment. document_idle comes after the page has
// loaded, so idle code runs as soon as its script does.
const CONTENT = [
  { moment: 'start', file: 'content-start.js', runAt: 'document_start' },
  { moment: 'idle', file: 'content-idle.js', runAt: 'document_idle' },
];

export function firefox(rules, { version }) {
  const sites = rules.map(rule => ({ rule, techniques: techniquesFor(rule, 'firefox') }));
  const content = CONTENT.map(c => ({ ...c, sites: sitesAt(sites, c.moment) }))
    .filter(c => c.sites.length);
  const files = {
    'manifest.json': JSON.stringify(manifest(sites, content, version), null, 2) + '\n',
    'background.js': background(sites),
    'icon.png': ICON,
    'LICENSE.txt': LICENSE,
    'options.html': optionsPage(rules.filter(rule => hasTechniques(rule, 'firefox'))),
    'options.js': optionsScript(),
  };
  for (const c of content) files[c.file] = contentScript(c.sites);
  return Object.fromEntries(
    Object.entries(files).map(([name, text]) => [`${FIREFOX_DIR}/${name}`, text]));
}

function manifest(sites, content, version) {
  return {
    manifest_version: 2,
    name: 'burlesco',
    version,
    description: 'Leia notícias sem ser assinante, burle o paywall',
    homepage_url: 'https://burles.co',
    author: 'rodorgas',
    icons: { 128: 'icon.png' },
    background: { scripts: ['background.js'] },
    content_scripts: content.map(c => ({
      matches: [...new Set(c.sites.flatMap(s => s.rule.matches))],
      js: [c.file],
      run_at: c.runAt,
    })),
    permissions: ['webRequest', 'webRequestBlocking', 'storage', ...hostPermissions(sites)],
    options_ui: { page: 'options.html' },
    browser_specific_settings: {
      gecko: {
        id: 'burlesco@burles.co',
        update_url: 'https://burlesco.github.io/burlesco-update/firefox.json',
      },
    },
  };
}

// Every URL a network Technique acts on, plus the pages of each Site that
// has one, so requests those pages start keep the whole-Site permission
// today's extension gives them. Exceptions sit inside those URLs.
function hostPermissions(sites) {
  const urls = sites.flatMap(({ rule, techniques: t }) => {
    const network = NETWORK.flatMap(key => t[key].flatMap(entry => entry.urls));
    return network.length ? [...rule.matches, ...network] : [];
  });
  return [...new Set(urls)].sort();
}

// The network Techniques as data, keyed by Site id, then the engine that
// carries them out.
function background(sites) {
  const network = {};
  for (const { rule, techniques: t } of sites) {
    if (NETWORK.every(key => isEmpty(t[key]))) continue;
    network[rule.id] = Object.fromEntries(NETWORK.map(key => [key, t[key]]));
  }
  return [
    '// Generated by the build from the Rules. Do not edit.',
    `const NETWORK = ${JSON.stringify(network, null, 2)};`,
    'const LISTENERS = [];',
    ...[...Object.values(engine), matchPatternToRegExp].map(fn => fn.toString()),
    'startNetwork();',
  ].join('\n\n') + '\n';
}

// The Sites with something to run at this moment, and what that is.
const sitesAt = (sites, moment) => sites
  .map(({ rule, techniques }) => ({ rule, statements: statementsAt(techniques, moment) }))
  .filter(s => s.statements.length);

// Each Site's code runs unless it is switched off in the options page. The
// choices are read first, as today's extension does.
function contentScript(sites) {
  const bySite = sites.map(s =>
    `if (sites[${JSON.stringify(s.rule.id)}] !== false) {\n` +
    `${indent(guarded(s.rule, s.statements), 2)}\n}`);
  return [
    '// Generated by the build from the Rules. Do not edit.',
    "browser.storage.local.get('sites').then(({ sites = {} }) => {\n" +
      `${indent(bySite.join('\n\n'), 2)}\n});`,
    ...Object.values(runtime).map(fn => fn.toString()),
  ].join('\n\n') + '\n';
}

// One switch per Site, named as people know it, in alphabetical order.
function optionsPage(rules) {
  const byName = [...rules].sort((a, b) => a.name.localeCompare(b.name, 'pt-BR'));
  const items = byName.map(rule =>
    `      <li><input type="checkbox" id="${rule.id}" checked>` +
    ` <label for="${rule.id}">${escapeHtml(rule.name)}</label></li>`);
  return [
    '<!doctype html>',
    '<!-- Generated by the build from the Rules. Do not edit. -->',
    '<html lang="pt-BR">',
    '<head>',
    '  <meta charset="utf-8">',
    '  <title>Burlesco</title>',
    '  <style>',
    '    body { font-family: sans-serif; margin: 1em; }',
    '    ul { list-style: none; padding: 0; columns: 2; }',
    '    li { margin: 0.25em 0; }',
    '  </style>',
    '</head>',
    '<body>',
    '  <h1>Sites</h1>',
    '  <p>Desmarque um site para o Burlesco não agir nele.</p>',
    '  <p>',
    '    <button type="button" id="all">Marcar todos</button>',
    '    <button type="button" id="none">Desmarcar todos</button>',
    '  </p>',
    '  <form>',
    '    <ul>',
    ...items,
    '    </ul>',
    '    <button type="submit" id="save">Salvar</button>',
    '  </form>',
    '  <script src="options.js"></script>',
    '</body>',
    '</html>',
  ].join('\n') + '\n';
}

function optionsScript() {
  return [
    '// Generated by the build. Do not edit.',
    ...Object.values(options).map(fn => fn.toString()),
    'startOptions();',
  ].join('\n\n') + '\n';
}

const escapeHtml = text => text
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

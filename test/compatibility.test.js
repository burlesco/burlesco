// Seam 1: the whole build, in memory. The generated COMPATIBILITY.md.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { build } from '../build/index.js';

// The table's rows, as { Site: { userscript, firefox } } cell text.
async function table(rules) {
  const files = await build(rules);
  const text = files['COMPATIBILITY.md'];
  assert.equal(typeof text, 'string', 'the build writes COMPATIBILITY.md');
  const lines = text.split('\n').filter(l => l.startsWith('|'));
  const [head, rule, ...rows] = lines.map(l =>
    l.slice(1, -1).split('|').map(c => c.trim()));
  assert.match(rule.join(''), /^[-: ]+$/);
  assert.deepEqual(head, ['Site', 'Userscript', 'Firefox']);
  return { text, rows: Object.fromEntries(rows.map(([site, userscript, firefox]) =>
    [site, { userscript, firefox }])) };
}

const alpha = {
  id: 'alpha',
  name: 'Alpha',
  matches: ['*://*.alpha.com/*'],
  blockRequests: [{ urls: ['*://paywall.alpha.com/*'] }],
  removeElements: ['.wall'],
  firefox: {
    blockCookies: { urls: ['*://*.alpha.com/*'] },
  },
};

const beta = {
  id: 'beta',
  name: 'Beta',
  matches: ['*://beta.org/*'],
  userscript: {
    siteIdle: () => {
      document.body.classList.remove('locked');
    },
  },
};

const gamma = { id: 'gamma', name: 'Gamma', matches: ['*://gamma.org/*'] };

test('each Site has a row listing its Techniques on each Target', async () => {
  const { rows } = await table([beta, alpha, gamma]);
  assert.deepEqual(Object.keys(rows), ['Alpha', 'Beta', 'Gamma']);
  assert.equal(rows.Alpha.firefox, '`blockRequests`, `blockCookies`, `removeElements`');
  assert.equal(rows.Beta.userscript, '`siteIdle`');
});

test('a Target with no Techniques for a Site shows as none', async () => {
  const { rows } = await table([beta, gamma]);
  assert.equal(rows.Beta.firefox, 'none');
  assert.deepEqual(rows.Gamma, { userscript: 'none', firefox: 'none' });
});

test('userscript request blocking carries the Tampermonkey 5.2+ on Chrome warning', async () => {
  const { rows, text } = await table([alpha, beta]);
  assert.equal(rows.Alpha.userscript, '`blockRequests`[^chrome], `removeElements`');
  assert.match(rows.Alpha.firefox, /^`blockRequests`,/, 'Firefox blocking has no warning');
  assert.match(text, /^\[\^chrome\]: .*Tampermonkey 5\.2\+.*Chrome/m);
});

test('the warning is left out when no Site blocks requests on the userscript', async () => {
  const { text } = await table([beta, gamma]);
  assert.doesNotMatch(text, /\[\^chrome\]/);
});

test('the table says it is generated, not edited by hand', async () => {
  const { text } = await table([gamma]);
  assert.match(text, /generated by `npm run build`/i);
});
